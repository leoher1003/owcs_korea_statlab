"""Write a COMP STATS sheet (composition frequency / mirror / win rate / favorite team) into a stage workbook.

Usage:
    python3 pipeline/build_comp_sheet.py OWCS_STAT_LAB_26_KR_STAGE3.xlsx

The numbers come from the comp_stats view in pipeline/sql/teamfights.sql (DuckDB). Run it after
export_site_data.py: saving with openpyxl drops Excel's cached formula results, so open the workbook
in Excel and save it once before the next export. Close the workbook in Excel before running.
"""
import os
import sys

import openpyxl
from openpyxl.styles import Alignment, Font, PatternFill

sys.path.insert(0, os.path.dirname(__file__))
import tf_db  # noqa: E402

SHEET = "COMP STATS"
HEADERS = ["Rank", "Tank", "DPS 1", "DPS 2", "Support 1", "Support 2",
           "Frequency", "Mirror", "W", "L", "W-L", "Win Rate", "Share", "Favorite Team", "All Teams"]
QUERY = """
    SELECT tank, dps1, dps2, support1, support2, freq, mirror, w, l, win_rate, fight_share,
           favorite_team, all_teams
    FROM comp_stats
    ORDER BY freq DESC, win_rate DESC NULLS LAST, comp_key
"""
NOTES = [
    "Frequency: team-side uses of the comp (a mirror fight counts twice, once per side).",
    "Mirror: teamfights where both teams played this comp. Excluded from W / L / Win Rate.",
    "Win Rate = W / (W + L). Share = fights in which the comp appeared / all fights (a mirror counts once).",
    "Comps are the same comp when they have the same five heroes (order ignored).",
    "Favorite Team: team that used the comp most often (ties listed together).",
    "Generated by pipeline/build_comp_sheet.py (SQL: pipeline/sql/teamfights.sql). Re-run after editing; manual edits here are overwritten.",
]


def main(path):
    lock = os.path.join(os.path.dirname(os.path.abspath(path)), "~$" + os.path.basename(path))
    if os.path.exists(lock):
        sys.exit("The workbook looks open in Excel (lock file found). Save and close it first.")

    con, problems = tf_db.load(path)
    if problems:
        sys.exit("Fix TEAMFIGHT INFO first:\n  " + "\n  ".join(problems))
    stats = con.execute(QUERY).fetchall()
    n_fights, n_mirror = con.execute(
        "SELECT (SELECT count(*) FROM teamfights), (SELECT sum(mirror) FROM comp_stats)").fetchone()

    wb = openpyxl.load_workbook(path)
    if SHEET in wb.sheetnames:
        del wb[SHEET]
    ws = wb.create_sheet(SHEET, index=wb.sheetnames.index("TEAMFIGHT INFO") + 1)
    ws.append(HEADERS)
    for rank, (t, d1, d2, s1, s2, freq, mirror, w, l, rate, share, fav, teams) in enumerate(stats, 1):
        ws.append([rank, t, d1, d2, s1, s2, freq, mirror, w, l, f"{w}-{l}", rate, share, fav, teams])

    header_fill = PatternFill("solid", fgColor="1F2937")
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center")
    for col in (12, 13):
        for row in ws.iter_rows(min_row=2, min_col=col, max_col=col):
            row[0].number_format = "0.0%"
    widths = [6, 13, 13, 13, 13, 13, 11, 8, 6, 6, 8, 10, 9, 18, 40]
    for i, w in enumerate(widths):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i + 1)].width = w
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = f"A1:{openpyxl.utils.get_column_letter(len(HEADERS))}{ws.max_row}"
    notes_col = len(HEADERS) + 2
    for i, note in enumerate(NOTES, 1):
        ws.cell(row=i, column=notes_col, value=note).font = Font(italic=True, color="6B7280")

    wb.calculation.fullCalcOnLoad = True
    wb.save(path)
    print(f"{SHEET}: {len(stats)} comps from {n_fights} teamfights ({n_mirror} mirror). "
          "Open the workbook in Excel and save it once.")


if __name__ == "__main__":
    main(sys.argv[1])
